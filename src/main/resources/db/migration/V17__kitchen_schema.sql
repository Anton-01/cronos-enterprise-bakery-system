CREATE OR REPLACE FUNCTION prevent_ingredient_price_modification() RETURNS TRIGGER AS $$
BEGIN
    RAISE EXCEPTION 'ingredient_prices is append-only: % is not permitted', TG_OP;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER ingredient_prices_append_only
    BEFORE UPDATE ON ingredient_prices
    FOR EACH ROW EXECUTE FUNCTION prevent_ingredient_price_modification();

