-- Plain-text instructions become an escaped paragraph of process HTML.
UPDATE recipes
SET process_html = '<p>' || replace(replace(replace(replace(btrim(instructions), '&', '&amp;'), '<', '&lt;'), '>', '&gt;'), E'\n', '<br>') || '</p>'
WHERE instructions IS NOT NULL AND btrim(instructions) <> '';

-- Unique names per owner among live rows: later duplicates get " (n)".
WITH ranked AS (
    SELECT id, row_number() OVER (PARTITION BY owner_id, kitchen_fold(name) ORDER BY created_at, id) AS n FROM recipes)
UPDATE recipes r SET name = left(r.name, 110) || ' (' || ranked.n || ')'
FROM ranked WHERE ranked.id = r.id AND ranked.n > 1;

WITH ranked AS (
    SELECT id, kitchen_code(name, 'RECIPE', 50) AS base,
           row_number() OVER (PARTITION BY owner_id, kitchen_code(name, 'RECIPE', 50) ORDER BY created_at, id) AS n
    FROM recipes)
UPDATE recipes r SET code = CASE WHEN ranked.n = 1 THEN ranked.base ELSE left(ranked.base, 44) || '_' || ranked.n END
FROM ranked WHERE ranked.id = r.id;

