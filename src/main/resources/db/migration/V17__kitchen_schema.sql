CREATE EXTENSION IF NOT EXISTS unaccent;
CREATE EXTENSION IF NOT EXISTS pg_trgm;

-- Accent/case folding usable in indexes (unaccent itself is only STABLE).
CREATE OR REPLACE FUNCTION kitchen_fold(value TEXT) RETURNS TEXT
    LANGUAGE sql IMMUTABLE PARALLEL SAFE STRICT
AS $$ SELECT lower(public.unaccent('public.unaccent'::regdictionary, value)) $$;

-- Stable code from free text: FOO_BAR, starts with a letter, 2..max chars.
CREATE OR REPLACE FUNCTION kitchen_code(value TEXT, fallback TEXT, max_length INT) RETURNS TEXT
    LANGUAGE sql IMMUTABLE PARALLEL SAFE
AS $$
SELECT CASE
           WHEN c IS NULL OR c = '' THEN fallback
           WHEN c !~ '^[A-Z]' THEN left(fallback || '_' || c, max_length)
           WHEN length(c) < 2 THEN c || '_X'
           ELSE left(c, max_length)
       END
FROM (SELECT btrim(upper(regexp_replace(kitchen_fold(coalesce(value, '')), '[^a-z0-9]+', '_', 'g')), '_') AS c) s
$$;

-- ─── legacy renames ─────────────────────────────────────────────────────────────────────
DO $$
DECLARE
    t TEXT;
    idx RECORD;
BEGIN
    FOREACH t IN ARRAY ARRAY['allergens', 'ingredient_substitutes', 'recipe_fixed_costs', 'recipe_files'] LOOP
        IF to_regclass('public.' || t) IS NOT NULL THEN
            FOR idx IN SELECT indexname FROM pg_indexes WHERE schemaname = 'public' AND tablename = t LOOP
                EXECUTE format('ALTER INDEX %I RENAME TO %I', idx.indexname, left('legacy_' || idx.indexname, 63));
            END LOOP;
            EXECUTE format('ALTER TABLE %I RENAME TO %I', t, 'legacy_' || t);
        END IF;
    END LOOP;
END $$;

